import { Router } from 'express';
import { authenticate, requireFamily, allowRoles } from '../middleware/auth.js';
import { uploadDocument } from '../middleware/upload.js';
import { validate } from '../utils/validation.js';
import { documentSchema, documentUpdateSchema, renewSchema } from '../validators/schemas.js';
import * as documents from '../controllers/documents.js';
const router = Router(); router.use(authenticate);
router.get('/categories', documents.categories);
router.get('/upcoming', requireFamily(), documents.upcomingDocuments);
router.get('/expired', requireFamily(), documents.expiredDocuments);
router.get('/', requireFamily(), documents.listDocuments);
router.post('/', uploadDocument, requireFamily(), allowRoles('keeper', 'backup'), validate(documentSchema), documents.createDocument);
router.get('/:id/versions/:versionNumber/download', requireFamily(), documents.downloadVersion);
router.get('/:id/versions', requireFamily(), documents.listVersions);
router.get('/:id/download', requireFamily(), documents.downloadDocument);
router.post('/:id/renew', uploadDocument, requireFamily(), validate(renewSchema), documents.renewDocument);
router.get('/:id', requireFamily(), documents.getDocument);
router.put('/:id', validate(documentUpdateSchema), requireFamily(), documents.updateDocument);
router.delete('/:id', requireFamily(), documents.archiveDocument);
export default router;
