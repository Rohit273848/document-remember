export function LanguageProvider({ children }) {
  const { user } = useAuth();
  const [language, setLanguageState] = useState(() => {
    const savedLanguage = localStorage.getItem('hearth-language');
    if (savedLanguage === 'hi' || savedLanguage === 'en') return savedLanguage;
    return navigator.language?.toLowerCase().startsWith('hi') ? 'hi' : 'en';
  });
  const languageWasSelected = useRef(false);
  const syncedLanguage = useRef(null);
  const setLanguage = (value) => {
    const next = value === 'hi' ? 'hi' : 'en'; languageWasSelected.current = true;
    localStorage.setItem('hearth-language', next); setLanguageState(next);
    if (user && user.language !== next) { syncedLanguage.current = next; api.put('/auth/profile', { language: next }).catch(() => { syncedLanguage.current = null; }); }
  };
  useEffect(() => {
    if (user?.language && !languageWasSelected.current) { localStorage.setItem('hearth-language', user.language); setLanguageState(user.language); }
    else if (user && languageWasSelected.current && user.language !== language && syncedLanguage.current !== language) {
      syncedLanguage.current = language;
      api.put('/auth/profile', { language }).catch(() => { syncedLanguage.current = null; });
    }
  }, [user?.language, language]);
  useEffect(() => { document.documentElement.lang = language; }, [language]);
  const value = useMemo(() => ({ language, setLanguage, t: (text, params = {}) => {
    if (language !== 'hi' || typeof text !== 'string') return Object.entries(params).reduce((result, [key, val]) => result.replaceAll(`{${key}}`, val ?? ''), text || '');
    let result = hi[text] || text;
    return Object.entries(params).reduce((output, [key, val]) => output.replaceAll(`{${key}}`, val ?? ''), result);
  } }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export const useLanguage = () => useContext(LanguageContext);

